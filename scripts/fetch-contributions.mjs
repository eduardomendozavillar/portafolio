#!/usr/bin/env node
/**
 * Refreshes the GitHub activity data for the heatmap (portfolio-rebrand S7).
 *
 * Uses the locally-authenticated `gh` CLI (GitHub GraphQL, contributions
 * collection = last 365 days) and regenerates `src/data/contributions.ts`.
 * No token ships with the app: the heatmap reads the static module, so a
 * stale calendar costs nothing and leaks nothing. Re-run after bursts:
 * `node scripts/fetch-contributions.mjs`.
 */
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const TARGET = path.resolve(fileURLToPath(new URL("../src/data/contributions.ts", import.meta.url)));
const LOGIN = "eduardomendozavillar";

const query = `query { user(login: "${LOGIN}") { contributionsCollection { contributionCalendar { totalContributions weeks { contributionDays { contributionCount date } } } } } }`;

function levelFor(count) {
  if (count <= 0) return 0;
  if (count <= 2) return 1;
  if (count <= 5) return 2;
  return 3;
}

const raw = execFileSync("gh", ["api", "graphql", "-f", `query=${query}`], {
  encoding: "utf8",
});
const parsed = JSON.parse(raw);
const calendar = parsed?.data?.user?.contributionsCollection?.contributionCalendar;
if (!calendar?.weeks) throw new Error("respuesta GraphQL inesperada");

const days = calendar.weeks.flatMap((week) =>
  week.contributionDays.map((day) => ({
    date: day.date,
    count: day.contributionCount,
  })),
);
const activeDays = days.filter((day) => day.count > 0).length;

const header =
  "/**\n" +
  " * GENERATED by `scripts/fetch-contributions.mjs` — do not edit by hand.\n" +
  ` * GitHub contribution calendar for ${LOGIN} (last 365 days, fetched via\n` +
  " * the authenticated `gh` CLI at build/refresh time; the deployed site\n" +
  " * only reads this static module — no tokens ship with it).\n" +
  " */\n\n";

const body =
  `export const contributionsTotal = ${calendar.totalContributions};\n\n` +
  `export const contributionsActiveDays = ${activeDays};\n\n` +
  `export const contributionsFetchedAt = ${JSON.stringify(new Date().toISOString())};\n\n` +
  "export type ContributionDay = { date: string; count: number; level: 0 | 1 | 2 | 3 };\n\n" +
  "export const contributionDays: ContributionDay[] = " +
  JSON.stringify(
    days.map((day) => ({ ...day, level: levelFor(day.count) })),
  ) +
  ";\n";

await writeFile(TARGET, header + body);
console.log(`contributions: ${calendar.totalContributions} total, ${activeDays} días activos → ${TARGET}`);
