#!/usr/bin/env node
/**
 * One-shot asset pipeline (run with `node scripts/optimize-project-images.mjs`):
 * converts the raw PNG screenshots in `img/<FOLDER>/` to optimized `.webp`
 * assets under `public/images/projects/<slug>/` and regenerates
 * `src/data/project-images.ts`, a typed manifest with intrinsic dimensions so
 * `next/image` can render them without layout shift.
 *
 * Source folders are Windows screenshots with spaces in their names; they are
 * renamed deterministically to `<slug>-<NN>.webp` in filename order.
 */
import { readdir, readFile, mkdir, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

/** Windows-safe path from a file URL (URL.pathname gives `C:\C:\...` there). */
function localPath(relativeUrl) {
  return path.resolve(fileURLToPath(new URL(relativeUrl, import.meta.url)));
}

const SOURCE_ROOT = localPath("../img");
const OUTPUT_ROOT = localPath("../public/images/projects");
const MANIFEST_TARGET = localPath("../src/data/project-images.ts");

const MAX_WIDTH = 1200;
const QUALITY = 78;

const FOLDER_TO_SLUG = {
  FITBOX: "fitbox-elite",
  SGDI: "sgdi",
  "TALLER.BY": "taller-by",
};

/** Serial ordering of the featured projects, matches github.ts presentation. */
const SLUG_ORDER = ["taller-by", "fitbox-elite", "sgdi"];

function fileBaseName(slug, index) {
  return `${slug}-${String(index + 1).padStart(2, "0")}`;
}

async function main() {
  const folders = await readdir(SOURCE_ROOT, { withFileTypes: true });
  const manifest = {};

  for (const folder of folders.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!folder.isDirectory()) continue;
    const slug = FOLDER_TO_SLUG[folder.name];
    if (!slug) {
      console.warn(`skip unrecognized folder: ${folder.name}`);
      continue;
    }

    const entries = (await readdir(path.join(SOURCE_ROOT, folder.name)))
      .filter((name) => name.toLowerCase().endsWith(".png"))
      .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));

    const outDir = path.join(OUTPUT_ROOT, slug);
    await rm(outDir, { recursive: true, force: true });
    await mkdir(outDir, { recursive: true });

    manifest[slug] = [];
    for (const [index, entry] of entries.entries()) {
      const input = path.join(SOURCE_ROOT, folder.name, entry);
      const base = fileBaseName(slug, index);
      const { data, info } = await sharp(input)
        .rotate()
        .resize({ width: MAX_WIDTH, withoutEnlargement: true })
        .webp({ quality: QUALITY })
        .toBuffer({ resolveWithObject: true });
      const file = `${base}.webp`;
      await writeFile(path.join(outDir, file), data);
      manifest[slug].push({
        src: `/images/projects/${slug}/${file}`,
        width: info.width,
        height: info.height,
      });
      console.log(`${entry} -> ${slug}/${file} (${info.width}x${info.height})`);
    }
  }

  const ordered = Object.fromEntries(
    SLUG_ORDER.filter((slug) => manifest[slug]).map((slug) => [slug, manifest[slug]]),
  );

  const header =
    "/**\n" +
    " * GENERATED by `scripts/optimize-project-images.mjs` — do not edit by hand.\n" +
    " * Intrinsic dimensions let the project preview render `next/image` without\n" +
    " * layout shift. Keys are project slugs (see src/data/github.ts).\n" +
    " */\n" +
    'import type { ProjectImage } from "@/types/project";\n\n';
  await writeFile(
    MANIFEST_TARGET,
    header + `export const projectImages: Record<string, ProjectImage[]> = ${JSON.stringify(ordered, null, 2)};\n`,
  );

  const count = Object.values(ordered).reduce((n, list) => n + list.length, 0);
  console.log(`done: ${count} webp assets, manifest written to src/data/project-images.ts`);
}

await main();
